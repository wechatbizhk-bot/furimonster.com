function fill(body, root) {
  let out = body;
  /* {{ROOT}} is replaced twice: once up front for template usage, and again at
   * the end for fragments that generate their own {{ROOT}} links. */
  out = out.replace(/\{\{ROOT\}\}/g, root || '');
  /* inline multilingual run: {{T:English|繁體|简体|ไทย|日本語}} */
  out = out.replace(/\{\{T:([\s\S]*?)\}\}/g, (all, payload) => {
    const parts = payload.split('|').map(s => s.trim());
    const field = {
      en: parts[0],
      'zh-Hant': parts[1] || parts[0],
      'zh-Hans': parts[2] || parts[1] || parts[0]
    };
    /* only set Thai/Japanese when the source actually carries them, so a
     * short run falls through to the translation table in T() instead of
     * being pinned to the English text */
    if (parts[3]) field.th = parts[3];
    if (parts[4]) field.ja = parts[4];
    return T(field);
  });
  /* character-specific fragments: {{IDENTITY:pinki}} */
  out = out.replace(/\{\{([A-Z_]+):([a-z-]+)\}\}/g, (all, name, slug) => {
    const ch = D.bySlug(slug);
    if (!ch) throw new Error('unknown character slug in fragment: ' + slug);
    const map = {
      IDENTITY: identity, ORIGINS: origins, CHAR_RELATIONS: charRelations,
      CHAR_STORIES: charStories, CHAR_GALLERY: charGallery,
      CHAR_DOWNLOADS: charDownloads, CHAR_NAV: charNav, CHAR_SWATCHES: charSwatches
    };
    if (!map[name]) throw new Error('unknown fragment: ' + name);
    return map[name](ch);
  });
  /* generic fragments */
  /* generic fragments — {{ROOT}} is deliberately excluded here and resolved below */
  out = out.replace(/\{\{(?!ROOT\}\})([A-Z_0-9]+)\}\}/g, (all, name) => {
    if (!FRAGMENTS[name]) {
      throw new Error('unknown fragment {{' + name + '}} — available: ' + Object.keys(FRAGMENTS).join(', '));
    }
    return FRAGMENTS[name]();
  });
  out = out.replace(/\{\{ROOT\}\}/g, root || '');
  return out;
}

