/* Build every pack archive. A pack whose images are missing produces no ZIP at
 * all rather than an empty one, and the page then omits the button. */
function stickerPackZips() {
  return (D.stickerPacks || []).map(pack => {
    const files = stickerPackFiles(pack);
    if (!files.length) return null;
    const entries = files.map(e => ({
      name: 'furimonster-' + pack.id + '/' + e.slug + '.png',
      data: fs.readFileSync(path.join(SITE, pack.dir, e.file))
    }));
    entries.push({
      name: 'furimonster-' + pack.id + '/README.txt',
      data: Buffer.from(packReadme(pack), 'utf8')
    });
    return { file: pack.zip, buf: zipStore(entries) };
  }).filter(Boolean);
}

