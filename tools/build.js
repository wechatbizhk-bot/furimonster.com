/* ---------- build ------------------------------------------------------- */
function build() {
  const written = [];
  const pageFiles = fs.readdirSync(PAGES_DIR)
    .filter(f => f.endsWith('.html') && !f.startsWith('_'));

  pageFiles.forEach(f => {
    const { meta, body } = parsePage(f);
    const root = meta.root || '';
    MT.setPage((meta.file || f).replace(/\\/g, '/'));
    const html = shell(meta, fill(body, root));
    written.push({ file: meta.file || f, html });
  });

  buildCharacterPages().forEach(p => written.push(p));
  buildComicPages().forEach(p => written.push(p));

  /* simple copy pages that need no fragments */
  ['privacy', 'terms', 'ai-content-notice'].forEach(name => {
    const f = '_' + name + '.html';
    if (!fs.existsSync(path.join(PAGES_DIR, f))) return;
    const { meta, body } = parsePage(f);
    MT.setPage(meta.file);
    written.push({ file: meta.file, html: shell(meta, fill(body, meta.root || '')) });
  });

  /* 404 */
  if (fs.existsSync(path.join(PAGES_DIR, '_404.html'))) {
    const { meta, body } = parsePage('_404.html');
    MT.setPage('404.html');
    written.push({ file: '404.html', html: shell(meta, fill(body, '')) });
  }

  /* sitemap + robots + llms.txt
   *
   * lastmod is the build date: every page here is generated, so a rebuild is
   * genuinely a change. priority follows the information architecture rather
   * than any ranking guarantee.
   *
   * The AI crawlers are named explicitly. Blocking them is the reflexive move
   * and would be wrong here: the whole point of the site is to be the
   * authoritative, quotable source for what FURI MONSTER is. */
  const builtOn = new Date().toISOString().slice(0, 10);
  const priorityFor = f =>
    f === 'index.html' ? '1.0'
      : f.indexOf('stories/') === 0 ? '0.5'
        : f.indexOf('characters/') === 0 ? '0.7'
          : '0.8';
  const urls = written
    .filter(w => w.file.endsWith('.html') && w.file !== '404.html')
    .map(w => `  <url>
    <loc>${CFG.url}/${w.file === 'index.html' ? '' : w.file}</loc>
    <lastmod>${builtOn}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>${priorityFor(w.file)}</priority>
  </url>`)
    .join('\n');
  written.push({
    file: 'sitemap.xml',
    html: `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`
  });
  written.push({
    file: 'robots.txt',
    html: `# ${CFG.url}
User-agent: *
Allow: /

# Build-time only — these are not part of the published site.
Disallow: /src/
Disallow: /tools/
Disallow: /README.md

# Answer engines are welcome to read the published pages.
User-agent: GPTBot
Allow: /
User-agent: OAI-SearchBot
Allow: /
User-agent: ClaudeBot
Allow: /
User-agent: Claude-Web
Allow: /
User-agent: PerplexityBot
Allow: /
User-agent: Google-Extended
Allow: /
User-agent: CCBot
Allow: /

Sitemap: ${CFG.url}/sitemap.xml
`
  });

  /* llms.txt — a short, factual map of the site for answer engines (the
   * emerging convention at llmstxt.org). Generated from the same data the pages
   * use, so it cannot drift out of step with them. */
  written.push({
    file: 'llms.txt',
    html: `# FURI MONSTER

> ${en(CFG.positioning)}

FURI MONSTER is a character IP: six guardians, one for each way anger needs to
move — seen, understood, expressed, released, transformed. The official site is
${CFG.url}.

## Key facts

- Creator: ${D.creator.name}
- Characters (6): ${D.characters.map(c => {
      const alt = c.nameAlt && c.nameAlt['zh-Hant'] && c.nameAlt['zh-Hant'] !== c.name
        ? ` (繁體 ${c.nameAlt['zh-Hant']}, 日本語 ${c.nameAlt.ja})` : '';
      return `${c.name} — ${en(c.role)}${alt}`;
    }).join('; ')}
- Tagline: ${en(CFG.tagline || D.brandTagline || '')}
- Languages: English, Traditional Chinese, Simplified Chinese, Thai, Japanese
- Four-panel comic library: ${COMICS ? COMICS.stories.length : 0} written scripts, in five languages
- Finished comics: ${(() => { try { return fs.readdirSync(path.join(SITE, 'assets', 'img', 'comics')).filter(f => f.endsWith('.webp')).length; } catch (e) { return 0; } })()} drawn four-panel comics (Traditional Chinese text is part of the artwork)
- Browser games: ${(D.games || []).filter(g => g.status === 'live').map(g => en(g.name)).join(', ')}${(D.games || []).filter(g => g.status !== 'live').length ? ` (in development: ${(D.games || []).filter(g => g.status !== 'live').map(g => en(g.name)).join(', ')})` : ''} — free, no login, no in-game purchases, and best scores stay on the visitor's own device

## Pages

${written.filter(w => w.file.endsWith('.html') && w.file !== '404.html' && w.file.indexOf('stories/') !== 0 && w.file.indexOf('characters/') !== 0)
        .map(w => `- [${w.file === 'index.html' ? 'Home' : w.file.replace('.html', '')}](${CFG.url}/${w.file === 'index.html' ? '' : w.file})`).join('\n')}

## Notes for citation

- Character names are written in Latin script in every language.
- The 120 four-panel comic scripts are machine translated and labelled as such.
- Items that are not yet real carry a visible label ("Concept", "Coming soon",
  "Sample"). Nothing on the site should be read as an announcement unless it is
  labelled as confirmed.
`
  });

  /* OG images are generated as PNG by tools/build-art.js, because social
   * scrapers do not render SVG. The build only verifies they are present and
   * wires the URLs; it must not regenerate them as SVG. */
  const ogDir = path.join(SITE, 'assets', 'img', 'og');
  const missingOg = [];
  D.characters.forEach(ch => {
    const f = path.join(ogDir, ch.slug + '.png');
    if (!fs.existsSync(f)) missingOg.push(ch.slug + '.png');
  });
  if (!fs.existsSync(path.join(ogDir, 'default.png'))) missingOg.push('default.png');
  if (missingOg.length && !CHECK) {
    console.warn('  ! missing OG images (' + missingOg.join(', ') + ') — run: node tools/build-art.js');
  }
  if (missingOg.length) {
    /* make it a hard failure: an OG tag pointing at a file that is not there
     * is exactly the kind of silent breakage this project keeps finding */
    throw new Error('missing Open Graph images: ' + missingOg.join(', ') +
      ' — run `node tools/build-art.js` to generate them from assets/img/ip/');
  }

  /* the sticker-pack archives, built from the same file lists the page renders */
  stickerPackZips().forEach(z => written.push(z));

  /* write */
  let total = 0;
  written.forEach(w => {
    const dest = path.join(SITE, w.file);
    total += w.buf ? w.buf.length : w.html.length;
    if (CHECK) return;
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    if (w.buf) fs.writeFileSync(dest, w.buf);
    else fs.writeFileSync(dest, w.html, 'utf8');
  });

  /* stories/ is wholly generated, so a page that is no longer in the model is
   * stale and has to go. Without this, a comic batch that fails to merge leaves
   * its previous pages on disk and the site keeps shipping stories that no
   * longer exist in the data — which is exactly how 20 untranslated winggo
   * stubs survived a green build. */
  if (!CHECK) {
    const storyDir = path.join(SITE, 'stories');
    if (fs.existsSync(storyDir)) {
      const expected = new Set(written
        .map(w => w.file.replace(/\\/g, '/'))
        .filter(f => f.indexOf('stories/') === 0));
      let removed = 0;
      fs.readdirSync(storyDir).forEach(f => {
        if (!f.endsWith('.html') || expected.has('stories/' + f)) return;
        fs.unlinkSync(path.join(storyDir, f));
        removed++;
      });
      if (removed) console.log(`  removed ${removed} stale page(s) that are no longer in the comic data`);
    }
  }

  return { written, total };
}

try {
  const res = build();
  const pages = res.written.filter(w => w.file.endsWith('.html')).length;
  console.log(`${CHECK ? '[check]' : 'built'} ${res.written.length} files (${pages} html pages), ${(res.total / 1024).toFixed(0)} KB`);

  /* Report the Thai/Japanese translation debt. This is deliberately loud: the
   * old behaviour was to serve English in its place and say nothing, which is
   * how 300-odd strings went missing without anyone noticing. */
  const missing = [...MT.missing].sort();
  const translated = Object.keys(MT.runs).length;
  /* The outstanding list is always written, including when it is empty, so a
   * stale file can never be mistaken for a clean one by tools/check.js. */
  const out = path.join(__dirname, 'mt-page-text.missing.json');
  const byPage = {};
  [...MT.byPage.keys()].sort().forEach(pg => {
    byPage[pg] = [...MT.byPage.get(pg)].sort();
  });
  fs.writeFileSync(out, JSON.stringify({
    _note: 'Outstanding Thai/Japanese strings, grouped by the page that ' +
      'first needs them. Fill th and ja, then merge the "runs" object ' +
      'into tools/mt-page-text.json. A string shared by several pages is ' +
      'listed under the first page that uses it.',
    _counts: { distinct: missing.length, pages: Object.keys(byPage).length },
    byPage: byPage,
    runs: missing.reduce((acc, s) => { acc[s] = { th: '', ja: '' }; return acc; }, {})
  }, null, 2) + '\n', 'utf8');

  if (missing.length) {
    console.log(`  ${translated} Thai/Japanese string(s) from tools/mt-page-text.json; ` +
      `${missing.length} distinct string(s) still fall back to English`);
  } else if (translated) {
    console.log(`  all ${translated} Thai/Japanese string(s) resolved — no English fallback remains`);
  }

  if (!process.env.FM_MT_QUIET) {
    res.written.filter(w => w.file.endsWith('.html')).forEach(w => console.log('  ' + w.file));
  }
} catch (e) {
  console.error('BUILD FAILED:', e.message);
  process.exit(1);
}
