/* ---------- front matter ------------------------------------------------- */
function parsePage(file) {
  const raw = fs.readFileSync(path.join(PAGES_DIR, file), 'utf8');
  const m = raw.match(/<!--FM([\s\S]*?)-->/);
  if (!m) throw new Error('no FM front-matter in ' + file);
  let meta;
  try { meta = JSON.parse(m[1]); }
  catch (e) { throw new Error('bad FM JSON in ' + file + ': ' + e.message); }
  return { meta, body: raw.slice(m[0].length) };
}

