/* Genuine FURI PLANET artwork: the six guardians together and guardians
 * standing on their own world. These are full-bleed scenes, so unlike the
 * character portraits they keep their backgrounds.
 *
 * The five lore beats above keep their placeholders: the supplied library has
 * no art depicting the planet before the extraction, the fleets arriving, or
 * the collapse, and filling those with unrelated art would contradict the text
 * they sit next to. */
function planetGallery() {
  if (!fs.existsSync(ART_DIR)) return '';
  const files = fs.readdirSync(ART_DIR)
    .filter(f => f.indexOf('world-') === 0 && f.endsWith('.webp'))
    .sort((a, b) => {
      /* the line-up leads, then the guardians in the site's character order */
      if (a === 'world-six-guardians.webp') return -1;
      if (b === 'world-six-guardians.webp') return 1;
      const order = ['furi-prince', 'pinki', 'winggo', 'fluffu', 'boxo', 'bubi'];
      const rank = f => order.findIndex(s => f.indexOf(s) !== -1);
      return rank(a) - rank(b);
    });
  if (!files.length) return '';
  const alt = esc(I.t('gallery.altSuffix', 'en'));
  return `<div class="gallery-grid gallery-grid--art">${files.map((f, i) => `
        <img class="art-img art-img--scene" src="{{ROOT}}assets/img/art/${f}" alt="FURI PLANET — ${alt}" loading="${i === 0 ? 'eager' : 'lazy'}" decoding="async" width="800" height="800">`).join('')}</div>`;
}

