/* ---------- small helpers ------------------------------------------------ */
function esc(s) {
  return String(s === null || s === undefined ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;')
    .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

/* ---------- machine-translated Thai and Japanese -------------------------- *
 * Thai and Japanese were never authored for most of this site: they were left
 * to fall back to English, which meant a Thai or Japanese visitor could pick
 * their language and still be shown English with no indication why.
 *
 * The table and the missing-string bookkeeping live in tools/mt.js so that
 * tools/forms.js — which emits the same language spans for the forms — cannot
 * drift into its own English fallback again. Run with FM_MT_REPORT=1 to write
 * the outstanding list to tools/mt-page-text.missing.json.
 * ------------------------------------------------------------------------- */
const MT = require('./mt.js');

/* Trilingual run, plus the Thai/Japanese table. All five languages are emitted;
 * CSS shows the active one. */
function T(field, cls) {
  const out = {};
  let missing = false;
  LOCALES.forEach(l => {
    let v = field[l];
    if (v === undefined || v === '') {
      if (l === 'th' || l === 'ja') {
        const mt = MT.lookup(field.en, l);
        if (mt === null) { missing = true; v = field.en; }
        else v = mt;
      } else {
        v = field.en;
      }
    }
    out[l] = v;
  });
  /* An empty payload is legitimately empty — a comic panel with no dialogue
   * produces one — so it is not translation debt and must not be reported. */
  if (missing && field.en) MT.note(field.en);
  return LOCALES.map(l =>
    `<span class="t ${cls || 't-inline'}" data-l="${l}">${esc(out[l])}</span>`
  ).join('');
}

/* Plain (single-language) = English, used inside attributes. */
function en(field) { return field && field.en ? field.en : String(field || ''); }

function badge(status) {
  const map = {
    concept: ['badge--concept', 'status.concept'],
    'coming-soon': ['badge--soon', 'status.comingSoon'],
    live: ['badge--live', 'status.live'],
    placeholder: ['badge--placeholder', 'status.placeholder']
  };
  const m = map[status] || map.concept;
  return `<span class="badge ${m[0]}">${esc(I.t(m[1], 'en'))}</span>`;
}

