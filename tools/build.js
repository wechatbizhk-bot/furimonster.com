function comicDesc(story, ch) {
  /* Search results truncate around 155-160 characters, so the description is
   * built to fit that. The story TITLE leads, because it is what makes all 120
   * descriptions unique — an earlier version opened with the themes and the
   * character, and collided whenever two stories happened to share both. The
   * scene follows, trimmed at a word boundary, when there is room for it. */
  const themes = story.tags.map(t => en(tagLabel(t))).filter(Boolean);
  const scene = String(en(story.panels[0].scene) || '').replace(/\s+/g, ' ').trim();
  const head = '“' + en(story.title) + '” — a four-panel FURI MONSTER comic starring ' + ch.name + '.';
  const themesPart = themes.length ? ' About ' + themes.join(', ') + '.' : '';
  const LIMIT = 158;
  let out = head + themesPart;
  const room = LIMIT - out.length - 1;
  if (room > 40 && scene) {
    out += ' ' + (scene.length <= room ? scene : scene.slice(0, room).replace(/\s+\S*$/, '') + '…');
  }
  if (out.length <= LIMIT) return out;
  return head.length <= LIMIT ? head : head.slice(0, LIMIT - 1) + '…';
}

/* One page per comic, generated from src/pages/_comic.html. */
function buildComicPages() {
  if (!COMICS) return [];
  const tplPath = path.join(PAGES_DIR, '_comic.html');
  if (!fs.existsSync(tplPath)) return [];
  const tpl = fs.readFileSync(tplPath, 'utf8');
  const m = tpl.match(/<!--FM([\s\S]*?)-->/);
  const baseMeta = JSON.parse(m[1]);
  const tplBody = tpl.slice(m[0].length);
  const out = [];

  COMICS.stories.forEach(story => {
    const ch = D.bySlug(story.character);
    if (!ch) return;
    MT.setPage('stories/' + story.id + '.html');
    const body = fill(tplBody
      .replace(/\{\{TITLE\}\}/g, T(story.title))
      .replace(/\{\{TITLE_EN\}\}/g, esc(en(story.title)))
      .replace(/\{\{COMIC_INDEX\}\}/g, '#' + String(story.index).padStart(2, '0'))
      .replace(/\{\{THEME\}\}/g, ch.theme.base)
      .replace(/\{\{CHARACTER_NAME\}\}/g, esc(ch.name))
      .replace(/\{\{CHARACTER_SLUG\}\}/g, ch.slug)
      .replace(/\{\{CHARACTER_ROLE\}\}/g, T(ch.role))
      .replace(/\{\{CHARACTER_ART\}\}/g, FM.art.monster(ch.slug, { target: 200, root: '{{ROOT}}' }))
      .replace(/\{\{COMIC_TAGS\}\}/g, comicTagChips(story.tags))
      .replace(/\{\{COMIC_PANELS\}\}/g, comicPanels(story))
      .replace(/\{\{COMIC_NAV\}\}/g, comicNav(story))
      , '../');

    const meta = Object.assign({}, baseMeta, {
      file: 'stories/' + story.id + '.html',
      canonical: 'stories/' + story.id + '.html',
      page: 'stories',
      root: '../',
      title: en(story.title) + ' — ' + ch.name,
      desc: comicDesc(story, ch),
      og: CFG.url + '/assets/img/og/' + ch.slug + '.png',
      jsonld: {
        '@context': 'https://schema.org', '@type': 'CreativeWork',
        name: en(story.title), inLanguage: LOCALES,
        isPartOf: { '@type': 'CreativeWorkSeries', name: 'FURI MONSTER four-panel comics' },
        url: CFG.url + '/stories/' + story.id + '.html',
        image: CFG.url + '/assets/img/og/' + ch.slug + '.png',
        creator: { '@type': 'Person', name: D.creator.name }
      }
    });
    out.push({ file: 'stories/' + story.id + '.html', html: shell(meta, body) });
  });
  return out;
}

