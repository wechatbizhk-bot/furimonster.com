/* The official-art manifest, as JSON that the games read at runtime.
 *
 * The guess game shows the real IP artwork — the same converted WebP files the
 * character galleries use. It needs to know which expression variants exist,
 * and that list is produced here by scanning the art directory, so a game can
 * never point at an image that was renamed or removed. */
function gameArtJson() {
  const map = {};
  D.characters.forEach(ch => {
    const files = charArtFiles(ch.slug);
    if (files.length) map[ch.slug] = files.map(f => 'assets/img/art/' + f);
  });
  return `<script type="application/json" id="fm-art-manifest">${JSON.stringify(map)}</script>`;
}

/* ---------- sticker packs ------------------------------------------------ *
 * The page and the "download all" ZIP are both derived from the files actually
 * sitting in assets/img/stickers and assets/img/ip-line, so the site cannot
 * advertise a sticker that is not there.
 *
 * The ZIP is written by hand with Node's Buffer instead of pulling in archiver
 * or jszip: the site ships with zero dependencies and build.js has no install
 * step, so a package here would break `node tools/build.js` on a clean clone.
 * PNG is already compressed, so the ZIP stores rather than deflates — which is
 * also why the method is 0 and no compression code is needed. */
const { zipStore } = require('./zip.js');
/* the six files a pack actually has, in the canonical character order */
function stickerPackFiles(pack) {
  const dir = path.join(SITE, pack.dir);
  if (!fs.existsSync(dir)) return [];
  return D.characters
    .map(ch => ({ slug: ch.slug, file: ch.slug + '.png' }))
    .filter(e => fs.existsSync(path.join(dir, e.file)));
}

